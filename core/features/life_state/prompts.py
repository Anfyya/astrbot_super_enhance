def place_description(raw: str) -> tuple[str, str]:
    """把配置里的地点名换成（规范名, 给模型看的地点说明）。

    作品里亚托莉那边的镇子没有正式名字，所以这里给的是描述而不是地名，
    免得模型自己编一个镇名出来。
    """
    name = str(raw or "").strip()
    name = _PLACE_ALIASES.get(name, name)
    if not name:
        name = "穗织"
    desc = PLACE_DESCRIPTIONS.get(name)
    if desc:
        return name, desc
    return name, "%s——主人和这几位角色一起去的地方" % name


def place_has_official_name(name: str) -> bool:
    """只有穗织是作品里真有名字的地点。"""
    return str(name or "").strip() == "穗织"

