BY_HOME = {"海边小镇": SEASIDE}


def localize(text: str, home: str) -> str:
    """把拼好的提示词里那几句宿舍说法换成住处的；没登记的住处原样返回。"""
    pairs = BY_HOME.get(str(home or "").strip())
    if not pairs or not text:
        return text
    for old, new in pairs:
        text = text.replace(old, new)
    return text
