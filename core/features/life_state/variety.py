def foil_reason(item: dict, ctx: dict | None, groups: dict | None = None, *, name: str = "", home: str = "") -> str:
    """仅当该条所有未通过门禁均为 discover（软受阻）且无任何 hard 门禁（如寒冬禁入、狂风暴雨）时，返回受阻原因。"""
    if not ctx or not isinstance(item, dict):
        return ""
    text = str(item.get("text") or "")
    grp = str(item.get("group") or "") or cool_key(text, groups)
    _base, _live, gates, _notes = _eval_gates(item, name, home, ctx)
    if not gates or any(kind != "discover" for _code, kind, _msg in gates):
        return ""
    code = gates[0][0]
    if code in ("wx_calm_bad", "wx_dive_bad", "wx_dive_murky", "wx_sub_bad"):
        return _FOIL_DISCOVER_TEXT[code]
    if code in ("wx_sunny_rain", "wx_sunny_cloud", "wx_sunny_wind", "wx_dry_rain", "wx_dry_wind"):
        if grp in _FOIL_DRY_GROUPS:
            return _FOIL_DISCOVER_TEXT[code]
    return ""


def foil_rows_for(
    items: list,
    name: str,
    home: str = "",
    work: bool = True,
    ctx: dict | None = None,
    groups: dict | None = None,
) -> dict[str, tuple[float, str]]:
    """返回当前被软受阻（零 hard 门禁）且适合写成『起念撞墙→临时作罢』的候选：{原文: (原始权重, 受阻原因)}。"""
    out: dict[str, tuple[float, str]] = {}
    if not ctx:
        return out
    for item in items or []:
        raw_w = _base_weight(item, name)
        if raw_w <= 0:
            continue
        why = foil_reason(item, ctx, groups, name=name, home=home)
        if why:
            out[item["text"]] = (float(raw_w), why)
    return out


class PoolStore:
    """插曲 / 消遣池（``pools.json``）。没有这个文件就用代码里的默认值。"""

    def __init__(self, path) -> None:
        self.path = Path(path)
        self._cache: tuple[int, dict] | None = None

    def custom(self) -> bool:
        return self.path.exists()

    def load(self) -> dict:
        if not self.path.exists():
            self._cache = None
            return default_pools()
        version = self.path.stat().st_mtime_ns
        if self._cache is not None and self._cache[0] == version:
            return self._cache[1]
        try:
            data = normalize_pools(jsonio.load(self.path, {}), merge_new_defaults=True)
        except Exception:
            return default_pools()
        self._cache = (version, data)
        return data

    def save(self, pools: dict) -> None:
        data = {kind: list(pools.get(kind) or []) for kind in POOL_KINDS}
        jsonio.save(self.path, data, indent=1)
        self._cache = (self.path.stat().st_mtime_ns, normalize_pools(data))

    def reset(self) -> None:
        if self.path.exists():
            self.path.unlink()
        self._cache = None


